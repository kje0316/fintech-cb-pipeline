-- Dimension Tables
-- 회사의 정적 정보를 저장하는 차원 테이블
CREATE TABLE IF NOT EXISTS dwh.dim_company (
    COMPANY_SK SERIAL PRIMARY KEY, 
    COMPANY_ID VARCHAR(255),
    FNDT_DT DATE,
    LISTD_DT DATE,
    LISTD_ABOL_DT DATE,
    SIC_CD_3 VARCHAR(255),
    CT_CNTY_GU_CD VARCHAR(255),
    WG_GB VARCHAR(255),
    AS1C10132 VARCHAR(255),
    ASCD10103 VARCHAR(255),
    AS1C20102 INTEGER,
    AS3C30110 NUMERIC,           -- 소유건축물실거래가합계
    ASCD10101 VARCHAR(255)       -- 소유건축물권리침해여부
);

-- 시간 정보를 저장하는 차원 테이블
CREATE TABLE IF NOT EXISTS dwh.dim_time (
    TIME_SK SERIAL PRIMARY KEY,
    BS_DT DATE NOT NULL
);

-- 업종 정보를 저장하는 차원 테이블
CREATE TABLE IF NOT EXISTS dwh.dim_industry (
    INDUSTRY_SK SERIAL PRIMARY KEY,
    INDUSTRY_CODE VARCHAR(10) NOT NULL UNIQUE,
    INDUSTRY_NAME VARCHAR(255) NOT NULL
);


